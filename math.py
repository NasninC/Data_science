import math
print(f"Pi:{math.pi}")
print(f"Euler's number:{math.e}")
print(f"Suare root of 64:{math.sqrt(64)}")
print(f"2 raised to power 3:{math.pow(2,3)}")
print(f"Natural log of e:{math.log10(100)}")
print(f"Ceiling of 4.2:{math.ceil(4.2)}")
print(f"Floor of 4.8:{math.floor(4.8)}")
print(f"Factorial of 5:{math.factorial(5)}")
print(f"GCD of 24 and 36:{math.gcd(24,36)}")
print(f"Absolute value of -7.5:{math.fabs(-7.5)}")
angle_degree=90
angle_radians=math.radians(angle_degree)
print(f"Sine of 90 degrees={math.sin(angle_radians)}")
